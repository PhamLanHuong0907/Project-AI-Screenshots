import fs from 'fs'
import path from 'path'
import chokidar, { FSWatcher } from 'chokidar'
import { clipboard } from 'electron'
import { EventEmitter } from 'events'
import { ScreenshotRepository } from '../database/screenshotRepository'
import { isSupportedImageFile, removeVietnameseDiacritics } from '../utils/fileUtils'
import { computeBufferSha256 } from '../utils/hashUtils'
import { AIService } from './aiService'
import { FileOrganizer } from './fileOrganizer'
import { MetadataService } from './metadataService'
import { SettingsService } from './settingsService'
import type { ScreenshotRecord, WatcherStatusEvent } from '../../renderer/src/types/screenshot'

interface QueueTask {
  screenshotId: string
  forceAI: boolean
  resolve: (record: ScreenshotRecord) => void
  reject: (err: Error) => void
}

export class ScreenshotWatcher extends EventEmitter {
  private watcher: FSWatcher | null = null
  private clipboardTimer: NodeJS.Timeout | null = null
  private lastClipboardHash: string = ''
  private lastFileDetectedAt = 0

  private repository: ScreenshotRepository
  private settingsService: SettingsService
  private metadataService: MetadataService
  private aiService: AIService
  private fileOrganizer: FileOrganizer

  private inFlightPaths = new Set<string>()
  private queue: QueueTask[] = []
  private activeWorkers = 0
  private isMonitoring = false
  private currentSourceFolder = ''

  constructor(
    repository: ScreenshotRepository,
    settingsService: SettingsService,
    metadataService: MetadataService,
    aiService: AIService,
    fileOrganizer?: FileOrganizer
  ) {
    super()
    this.repository = repository
    this.settingsService = settingsService
    this.metadataService = metadataService
    this.aiService = aiService
    this.fileOrganizer = fileOrganizer || new FileOrganizer(repository, settingsService)
  }

  public markPathInFlight(filePath: string): void {
    const resolved = path.resolve(filePath)
    this.inFlightPaths.add(resolved)
    // Release after 3 seconds when fs events have settled
    setTimeout(() => {
      this.inFlightPaths.delete(resolved)
    }, 3000)
  }

  public getStatus(): WatcherStatusEvent {
    return {
      isMonitoring: this.isMonitoring,
      sourceFolder: this.currentSourceFolder || this.settingsService.getPublicSettings().sourceFolder
    }
  }

  /**
   * Starts monitoring the configured screenshot source folder with Chokidar (REQ01)
   * and optionally monitors the Windows Clipboard for `Win + Shift + S` snips.
   */
  public async start(customFolder?: string): Promise<WatcherStatusEvent> {
    await this.stop()

    const settings = this.settingsService.getPublicSettings()
    const targetFolder = path.resolve(customFolder || settings.sourceFolder)
    this.currentSourceFolder = targetFolder

    try {
      if (!fs.existsSync(targetFolder)) {
        await fs.promises.mkdir(targetFolder, { recursive: true })
      }
    } catch (err) {
      const errorMsg = `Cannot access or create source folder "${targetFolder}": ${(err as Error).message}`
      this.isMonitoring = false
      this.settingsService.setMonitoringState(false)
      const status: WatcherStatusEvent = {
        isMonitoring: false,
        sourceFolder: targetFolder,
        error: errorMsg
      }
      this.emit('status', status)
      return status
    }

    this.watcher = chokidar.watch(targetFolder, {
      ignoreInitial: true,
      depth: 0,
      persistent: true,
      awaitWriteFinish: {
        stabilityThreshold: 800,
        pollInterval: 150
      },
      ignorePermissionErrors: true
    })

    this.watcher.on('add', (filePath: string) => {
      this.lastFileDetectedAt = Date.now()
      // Skip files that were just generated by our own clipboard capture
      if (this.inFlightPaths.has(path.resolve(filePath))) {
        return
      }
      void this.handleNewFileDetected(filePath)
    })

    this.watcher.on('unlink', (filePath: string) => {
      this.handleFileDeletedExternally(filePath)
    })

    this.watcher.on('error', (error: Error) => {
      console.error('Chokidar watcher error:', error)
      this.emit('status', {
        isMonitoring: this.isMonitoring,
        sourceFolder: targetFolder,
        error: error.message
      } satisfies WatcherStatusEvent)
    })

    this.startClipboardPolling()

    this.isMonitoring = true
    this.settingsService.setMonitoringState(true)
    const status: WatcherStatusEvent = {
      isMonitoring: true,
      sourceFolder: targetFolder
    }
    this.emit('status', status)
    return status
  }

  public async stop(): Promise<WatcherStatusEvent> {
    this.stopClipboardPolling()
    if (this.watcher) {
      try {
        await this.watcher.close()
      } catch (err) {
        console.error('Error closing watcher:', err)
      }
      this.watcher = null
    }
    this.isMonitoring = false
    this.settingsService.setMonitoringState(false)
    const status: WatcherStatusEvent = {
      isMonitoring: false,
      sourceFolder: this.currentSourceFolder || this.settingsService.getPublicSettings().sourceFolder
    }
    this.emit('status', status)
    return status
  }

  /**
   * Captures an image currently in the Windows Clipboard (e.g. from `Win + Shift + S`),
   * saves it into the monitored Screenshots folder, and triggers AI analysis.
   */
  public async captureFromClipboard(manual = true): Promise<{
    captured: boolean
    message: string
    screenshot?: ScreenshotRecord
  }> {
    try {
      if (!clipboard || typeof clipboard.readImage !== 'function') {
        return {
          captured: false,
          message: 'Clipboard API is only available inside the Electron desktop runtime.'
        }
      }

      const nativeImg = clipboard.readImage()
      if (!nativeImg || nativeImg.isEmpty()) {
        return {
          captured: false,
          message:
            'No screenshot image found in the Windows Clipboard. Press Win + Shift + S or PrtScn first!'
        }
      }

      const pngBuffer = nativeImg.toPNG()
      if (!pngBuffer || pngBuffer.length === 0) {
        return {
          captured: false,
          message: 'Clipboard image buffer is empty.'
        }
      }

      const clipHash = computeBufferSha256(pngBuffer)
      this.lastClipboardHash = clipHash

      // If triggered automatically by clipboard polling, check if this image was just saved to disk by Windows Snipping Tool
      if (!manual) {
        const existingHashMatches = this.repository.findByHash(clipHash)
        if (existingHashMatches.length > 0) {
          return {
            captured: false,
            message: 'Clipboard screenshot already exists in database.'
          }
        }
      }

      const settings = this.settingsService.getPublicSettings()
      const targetFolder = path.resolve(settings.sourceFolder)
      if (!fs.existsSync(targetFolder)) {
        await fs.promises.mkdir(targetFolder, { recursive: true })
      }

      const timestamp = new Date()
        .toISOString()
        .replace(/[:.]/g, '-')
        .replace('T', '_')
        .slice(0, 19)
      const fileName = `Screenshot_${timestamp}.png`
      const fullPath = path.join(targetFolder, fileName)

      // Register path in inFlightPaths BEFORE writing to prevent chokidar watcher from firing duplicate event
      this.inFlightPaths.add(fullPath)
      await fs.promises.writeFile(fullPath, pngBuffer)
      const record = await this.handleNewFileDetected(fullPath)

      return {
        captured: true,
        message: `Captured screenshot from Clipboard (${fileName}) and started AI analysis!`,
        screenshot: record || undefined
      }
    } catch (err) {
      return {
        captured: false,
        message: `Failed to capture screenshot from clipboard: ${(err as Error).message}`
      }
    }
  }

  private startClipboardPolling(): void {
    this.stopClipboardPolling()
    try {
      if (clipboard && typeof clipboard.readImage === 'function') {
        const initialImg = clipboard.readImage()
        if (initialImg && !initialImg.isEmpty()) {
          this.lastClipboardHash = computeBufferSha256(initialImg.toPNG())
        }
      }
    } catch {
      // Ignore outside Electron runtime
      return
    }

    this.clipboardTimer = setInterval(() => {
      try {
        const settings = this.settingsService.getPublicSettings()
        if (!settings.watchClipboard || !this.isMonitoring) return
        if (!clipboard || typeof clipboard.readImage !== 'function') return

        const img = clipboard.readImage()
        if (!img || img.isEmpty()) return

        const pngBuf = img.toPNG()
        const hash = computeBufferSha256(pngBuf)
        if (!hash || hash === this.lastClipboardHash) return

        this.lastClipboardHash = hash

        // Wait 1.4s to let Windows Snipping Tool write to Pictures\Screenshots if auto-save is enabled in Windows
        setTimeout(() => {
          const recentlySavedFile = Date.now() - this.lastFileDetectedAt < 2500
          const alreadyInDb = this.repository.findByHash(hash).length > 0
          if (!recentlySavedFile && !alreadyInDb) {
            void this.captureFromClipboard(false)
          }
        }, 1400)
      } catch {
        // Ignore transient clipboard lock errors
      }
    }, 1800)
  }

  private stopClipboardPolling(): void {
    if (this.clipboardTimer) {
      clearInterval(this.clipboardTimer)
      this.clipboardTimer = null
    }
  }

  /**
   * Optional explicit scan of existing files in the source directory when requested by the user (REQ01).
   */
  public async scanExistingFiles(): Promise<{ added: number; skipped: number }> {
    const settings = this.settingsService.getPublicSettings()
    const folder = path.resolve(settings.sourceFolder)

    if (!fs.existsSync(folder)) {
      return { added: 0, skipped: 0 }
    }

    const entries = await fs.promises.readdir(folder, { withFileTypes: true })
    let added = 0
    let skipped = 0

    for (const entry of entries) {
      if (!entry.isFile()) continue
      const fullPath = path.join(folder, entry.name)
      if (!isSupportedImageFile(fullPath)) {
        skipped++
        continue
      }

      const existing = this.repository.findByOriginalPath(fullPath)
      if (existing || this.inFlightPaths.has(fullPath)) {
        skipped++
        continue
      }

      const created = await this.handleNewFileDetected(fullPath)
      if (created) {
        added++
      } else {
        skipped++
      }
    }

    return { added, skipped }
  }

  /**
   * Handles a newly detected file in the monitored folder.
   */
  public async handleNewFileDetected(rawFilePath: string): Promise<ScreenshotRecord | null> {
    const filePath = path.resolve(rawFilePath)

    if (!isSupportedImageFile(filePath)) {
      return null
    }

    if (this.inFlightPaths.has(filePath)) {
      return null
    }

    // Prevent processing the same file path (or an already renamed final_path) multiple times
    const existingByPath = this.repository.findByOriginalPath(filePath)
    if (existingByPath && existingByPath.status !== 'failed') {
      return null
    }

    this.inFlightPaths.add(filePath)

    try {
      const settings = this.settingsService.getPublicSettings()
      const meta = await this.metadataService.extractMetadata(filePath, settings.maxImageSizeMB)

      // Check if an identical screenshot (by SHA-256 hash) was already analyzed
      const duplicateMatch = this.repository.findAnalyzedByHash(meta.fileHash)

      let record: ScreenshotRecord
      if (existingByPath && existingByPath.status === 'failed') {
        record = this.repository.update(existingByPath.id, {
          file_hash: meta.fileHash,
          file_size: meta.sizeBytes,
          width: meta.width,
          height: meta.height,
          status: 'pending',
          error_message: ''
        })
      } else if (duplicateMatch) {
        // Reuse existing analysis without making a duplicate AI Vision request (REQ02 & Section 10)
        record = this.repository.create({
          original_name: meta.originalName,
          original_path: meta.originalPath,
          file_hash: meta.fileHash,
          suggested_name: duplicateMatch.suggested_name,
          category: duplicateMatch.category,
          description: duplicateMatch.description,
          tags: duplicateMatch.tags,
          confidence: duplicateMatch.confidence,
          status: 'review',
          file_size: meta.sizeBytes,
          width: meta.width,
          height: meta.height,
          is_duplicate: true,
          duplicate_of_id: duplicateMatch.id
        })
        this.repository.logHistory(
          record.id,
          'duplicate_detected',
          `Matched SHA-256 hash of screenshot ${duplicateMatch.id}; reused AI analysis.`
        )

        if (settings.autoApplyRename) {
          record = await this.autoRenameIfEnabled(record)
        }

        this.emit('new-screenshot', record)
        return record
      } else {
        record = this.repository.create({
          original_name: meta.originalName,
          original_path: meta.originalPath,
          file_hash: meta.fileHash,
          status: 'pending',
          file_size: meta.sizeBytes,
          width: meta.width,
          height: meta.height
        })
      }

      this.emit('new-screenshot', record)

      // Enqueue for AI Vision analysis
      void this.enqueueAnalysis(record.id, false).catch((err) => {
        console.error(`Background analysis error for ${record.id}:`, err)
      })

      return record
    } catch (err) {
      console.error(`Failed to ingest new screenshot "${filePath}":`, err)
      return null
    } finally {
      this.inFlightPaths.delete(filePath)
    }
  }

  /**
   * Enqueues a screenshot for AI analysis with concurrency control (Section 11).
   */
  public enqueueAnalysis(screenshotId: string, forceAI = false): Promise<ScreenshotRecord> {
    return new Promise((resolve, reject) => {
      this.queue.push({
        screenshotId,
        forceAI,
        resolve,
        reject
      })
      this.processQueue()
    })
  }

  private processQueue(): void {
    const maxConcurrency = Math.max(
      1,
      this.settingsService.getPublicSettings().maxConcurrency || 2
    )

    while (this.activeWorkers < maxConcurrency && this.queue.length > 0) {
      const task = this.queue.shift()!
      this.activeWorkers++

      this.runAnalysisTask(task.screenshotId, task.forceAI)
        .then((record) => task.resolve(record))
        .catch((err) => task.reject(err))
        .finally(() => {
          this.activeWorkers--
          this.processQueue()
        })
    }
  }

  private async runAnalysisTask(screenshotId: string, forceAI: boolean): Promise<ScreenshotRecord> {
    const record = this.repository.findById(screenshotId)
    if (!record) {
      throw new Error(`Screenshot not found: ${screenshotId}`)
    }

    const activePath =
      record.final_path && fs.existsSync(record.final_path)
        ? record.final_path
        : record.original_path

    if (!fs.existsSync(activePath)) {
      const failed = this.repository.update(screenshotId, {
        status: 'failed',
        error_message: 'Source screenshot file no longer exists on disk.'
      })
      this.emit('screenshot-updated', failed)
      return failed
    }

    // Check duplicate hash again before calling AI unless user explicitly requested a retry
    if (!forceAI && record.file_hash) {
      const duplicateMatch = this.repository.findAnalyzedByHash(record.file_hash, record.id)
      if (duplicateMatch) {
        let updatedDup = this.repository.update(record.id, {
          suggested_name: duplicateMatch.suggested_name,
          category: duplicateMatch.category,
          description: duplicateMatch.description,
          tags: duplicateMatch.tags,
          confidence: duplicateMatch.confidence,
          status: 'review',
          is_duplicate: true,
          duplicate_of_id: duplicateMatch.id,
          error_message: ''
        })
        updatedDup = await this.autoRenameIfEnabled(updatedDup)
        this.emit('screenshot-updated', updatedDup)
        return updatedDup
      }
    }

    const currentSettingsForMode = this.settingsService.getPublicSettings()
    if (currentSettingsForMode.manualRenameOnly && !forceAI) {
      let defaultCat = 'Others'
      const destDir = currentSettingsForMode.destinationFolder
      if (currentSettingsForMode.useDefaultCategories === false && destDir && fs.existsSync(destDir)) {
        try {
          const dirs = fs
            .readdirSync(destDir, { withFileTypes: true })
            .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
            .map((e) => e.name)
          if (dirs.length > 0) {
            const hasOthers = dirs.find((d) => /^(others|khac|khác|chung)$/i.test(d))
            defaultCat = hasOthers || dirs[0]
          }
        } catch {
          // Ignore
        }
      }

      const baseOriginalName = path.basename(activePath, path.extname(activePath))
      const manualReady = this.repository.update(screenshotId, {
        suggested_name: baseOriginalName,
        category: defaultCat,
        description: 'Chế độ tự đặt tên thủ công (không dùng AI).',
        tags: ['Manual'],
        confidence: 1,
        status: 'review',
        error_message: ''
      })
      this.repository.logHistory(
        screenshotId,
        'manual_review_ready',
        `Ready for manual naming (${defaultCat})`
      )
      this.emit('screenshot-updated', manualReady)
      return manualReady
    }

    const analyzingRecord = this.repository.update(screenshotId, {
      status: 'analyzing',
      error_message: ''
    })
    this.emit('screenshot-updated', analyzingRecord)

    try {
      const analysis = await this.aiService.analyzeScreenshot(activePath)

      // Match AI suggested category against existing disk directories
      const currentSettings = this.settingsService.getPublicSettings()
      const useDefaults = currentSettings.useDefaultCategories !== false
      let matchedCategory = analysis.category || 'Others'
      const destDir = currentSettings.destinationFolder
      const existingDirs: string[] = []

      if (destDir && fs.existsSync(destDir)) {
        try {
          const topEntries = fs.readdirSync(destDir, { withFileTypes: true })
          for (const entry of topEntries) {
            if (!entry.isDirectory() || entry.name.startsWith('.')) continue
            existingDirs.push(entry.name)
            try {
              const subEntries = fs.readdirSync(path.join(destDir, entry.name), { withFileTypes: true })
              for (const sub of subEntries) {
                if (sub.isDirectory() && !sub.name.startsWith('.')) {
                  existingDirs.push(`${entry.name}/${sub.name}`)
                }
              }
            } catch {
              // Ignore unreadable subdirectory
            }
          }
        } catch {
          // Ignore
        }
      }

      const candidateFolders =
        existingDirs.length > 0
          ? existingDirs
          : !useDefaults && currentSettings.customCategories?.length
            ? currentSettings.customCategories
            : []

      if (candidateFolders.length > 0) {
        const directMatch = candidateFolders.find(
          (d) =>
            d.toLowerCase() === (analysis.category || '').toLowerCase() ||
            d.toLowerCase() === (analysis.category || '').split('/')[0].toLowerCase()
        )
        if (directMatch) {
          matchedCategory = directMatch
        } else if (!useDefaults) {
          // Score existing folders against AI category, tags, description, and suggestedName
          const contextText = removeVietnameseDiacritics(
            `${analysis.category || ''} ${analysis.suggestedName || ''} ${analysis.description || ''} ${(analysis.tags || []).join(' ')}`
          ).toLowerCase()

          let bestFolder = ''
          let bestScore = 0
          for (const folder of candidateFolders) {
            const tokens = removeVietnameseDiacritics(folder)
              .toLowerCase()
              .split(/[^a-z0-9]+/)
              .filter((t) => t.length >= 2)
            let score = 0
            for (const tok of tokens) {
              if (contextText.includes(tok)) {
                score += tok.length
              }
            }
            if (score > bestScore) {
              bestScore = score
              bestFolder = folder
            }
          }

          if (bestFolder && bestScore > 0) {
            matchedCategory = bestFolder
          } else {
            const hasOthers = candidateFolders.find((d) =>
              /^(others|khac|khác|chung)$/i.test(d)
            )
            matchedCategory = hasOthers || candidateFolders[0]
          }
        }
      } else if (!useDefaults) {
        matchedCategory = 'Others'
      }

      let completed = this.repository.update(screenshotId, {
        suggested_name: analysis.suggestedName,
        category: matchedCategory,
        description: analysis.description,
        tags: analysis.tags,
        confidence: analysis.confidence,
        status: 'review',
        error_message: ''
      })
      this.repository.logHistory(
        screenshotId,
        'ai_analysis_success',
        `Suggested: ${analysis.suggestedName} (${matchedCategory})`
      )

      completed = await this.autoRenameIfEnabled(completed)
      this.emit('screenshot-updated', completed)
      return completed
    } catch (err) {
      const errMessage = (err as Error).message || 'AI analysis failed'
      const failed = this.repository.update(screenshotId, {
        status: 'failed',
        error_message: errMessage
      })
      this.repository.logHistory(screenshotId, 'ai_analysis_failed', errMessage)
      this.emit('screenshot-updated', failed)
      return failed
    }
  }

  /**
   * When `autoApplyRename` is enabled by the user, automatically renames/organizes
   * the screenshot immediately after AI analysis completes.
   */
  private async autoRenameIfEnabled(record: ScreenshotRecord): Promise<ScreenshotRecord> {
    const settings = this.settingsService.getPublicSettings()
    if (!settings.autoApplyRename || !record.suggested_name) {
      return record
    }

    try {
      return await this.fileOrganizer.confirmAndOrganize({
        id: record.id,
        finalName: record.suggested_name,
        category: record.category || 'Others',
        description: record.description || '',
        tags: record.tags || []
      })
    } catch (err) {
      console.error(`Auto-rename failed for ${record.id}:`, err)
      return record
    }
  }

  private handleFileDeletedExternally(rawFilePath: string): void {
    const filePath = path.resolve(rawFilePath)
    const existing = this.repository.findByOriginalPath(filePath)
    if (!existing) return

    // If the file was already organized/renamed to final_path, its old original_path unlink is expected
    if (existing.status === 'saved' || (existing.final_path && fs.existsSync(existing.final_path))) {
      return
    }

    if (
      existing.status === 'pending' ||
      existing.status === 'analyzing' ||
      existing.status === 'review'
    ) {
      const updated = this.repository.update(existing.id, {
        status: 'failed',
        error_message: 'Source file was deleted or moved externally before review confirmation.'
      })
      this.emit('screenshot-updated', updated)
    }
  }
}
